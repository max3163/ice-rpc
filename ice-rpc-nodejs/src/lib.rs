//! `ice-rpc-nodejs` — the reusable Node.js engine for ice-rpc services.
//!
//! It lets a Node.js process **provide** and **consume** ice-rpc services: the
//! business logic stays in JavaScript, the IPC transport stays in Rust over
//! iceoryx2 shared memory. This is the reusable engine; it holds **no concrete
//! service**. The list of services is supplied by the addon, through the
//! [`gateway!`] macro, which also emits the N-API surface.
//!
//! # Building an addon
//!
//! An addon is a small `cdylib` crate that depends on this one and names its
//! services:
//!
//! ```rust,ignore
//! ice_rpc_nodejs::gateway! {
//!     my_services::ConfigServiceProxy,
//!     my_services::OrdersServiceProxy,
//! }
//! ```
//!
//! See the crate's `Readme.md` for the `Cargo.toml`, `build.rs` and npm layout,
//! and `docs/nodejs-gateway-api-v3.md` for the JavaScript contract (argument
//! convention, event envelope, error codes, lifecycle).
//!
//! # Why the list is not here
//!
//! A precompiled addon cannot serve an arbitrary set of services: the rkyv ↔ JSON
//! conversions of each service are generated by `#[service]` and must be linked
//! into the `.node`. The service set is therefore a **compile-time** property of
//! the addon, which is why this crate takes it as a parameter rather than
//! hard-coding one.
//!
//! # Threading
//!
//! `callService` and `callServiceStream` run their IPC call on the libuv thread
//! pool, so they never block the Node.js event loop. The reverse direction does
//! block: the transport dispatch thread waits for the JS dispatcher, which is why
//! that wait is bounded (`ice_rpc::json::JSON_CALL_TIMEOUT`) and the pending
//! table is capped.

