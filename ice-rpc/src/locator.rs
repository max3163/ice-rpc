//! Central service registry (Service Locator pattern).
//!
//! Providers call [`ServiceLocator::register`] (via `run_provider!`); consumers
//! are instantiated lazily on the first [`ServiceLocator::get`]. Service
//! discovery and the transport itself are handled by iceoryx2.

use std::any::Any;
use std::collections::{HashMap, HashSet};
use std::sync::Arc;

use async_lock::RwLock;

use crate::global::Global;
use crate::service_traits::{ServiceConsumer, ServiceInit, ServiceLifecycle, ServiceNamed};

/// Groups the facets of a registered service.
#[derive(Clone)]
struct ServiceEntry {
    instance: Arc<dyn Any + Send + Sync>,
    lifecycle: Arc<dyn ServiceLifecycle>,
    init: Arc<dyn ServiceInit>,
}

/// Central registry of the application services (Service Locator pattern).
pub struct ServiceLocator {
    /// Services explicitly registered via [`register`](Self::register)
    /// (Providers). Only these are initialized by
    /// [`initialize_all`](Self::initialize_all).
    entries: RwLock<HashMap<&'static str, ServiceEntry>>,
    /// Cache of Consumer proxies instantiated lazily via
    /// [`get`](Self::get).
    lazy_cache: RwLock<HashMap<&'static str, Arc<dyn Any + Send + Sync>>>,
    /// Blocking IPC thread handles joined at shutdown.
    shutdown_registry: crate::shutdown::ShutdownRegistry,
}

impl ServiceLocator {
    /// Returns the unique global instance of the [`ServiceLocator`] (singleton).
    pub fn global() -> &'static Self {
        static INSTANCE: Global<ServiceLocator> = Global::new();
        INSTANCE.get_or_init(|| Self {
            entries: RwLock::new(HashMap::new()),
            lazy_cache: RwLock::new(HashMap::new()),
            shutdown_registry: crate::shutdown::ShutdownRegistry::new(),
        })
    }

    /// Builds a **fresh, empty** registry, independent of the process-wide
    /// singleton.
    ///
    /// Test-only: it lets a test assert absolute counts and identities without
    /// observing what another test registered. Production code always goes
    /// through [`global`](Self::global).
    #[cfg(test)]
    pub(crate) fn new_for_test() -> Self {
        Self {
            entries: RwLock::new(HashMap::new()),
            lazy_cache: RwLock::new(HashMap::new()),
            shutdown_registry: crate::shutdown::ShutdownRegistry::new(),
        }
    }

    /// Returns the number of currently registered services.
    pub fn service_count(&self) -> u8 {
        self.entries.try_read().map(|e| e.len() as u8).unwrap_or(0)
    }

    /// Returns the logical names of all the registered local services.
    pub fn service_names(&self) -> Vec<&'static str> {
        self.entries
            .try_read()
            .map(|e| e.keys().copied().collect())
            .unwrap_or_default()
    }

    /// Registers a blocking IPC thread handle in the shutdown registry.
    pub fn register_shutdown_handle(&self, handle: crate::rt::BlockingHandle) {
        self.shutdown_registry.register(handle);
    }

    /// Registers a dispatch thread owning iceoryx2 ports in the shutdown registry.
    ///
    /// The ports are dropped when the thread returns, and dropping them is what
    /// unlinks the shared-memory files of the services it created. A process that
    /// exits without waiting for these threads therefore leaves its services
    /// behind — on a clean shutdown, not only after a kill.
    pub fn register_shutdown_thread(&self, handle: std::thread::JoinHandle<()>) {
        self.shutdown_registry.register_thread(handle);
    }

    /// Waits for the registered blocking threads and releases the node.
    pub async fn release_node(&self) {
        self.shutdown_registry.join_all().await;
    }

    /// Waits for the registered IPC threads, **blocking the current thread**.
    ///
    /// Synchronous twin of [`release_node`](Self::release_node), for a consumer
    /// that runs no async runtime: it joins the dispatch threads at exit so the
    /// iceoryx2 ports are dropped and their shared-memory files unlinked.
    pub fn release_node_blocking(&self) {
        crate::rt::block_on(self.release_node());
    }

    /// Retrieves a proxy by its **type** and returns it ready to use.
    ///
    /// If the proxy is not yet cached, it is instantiated via
    /// [`ServiceConsumer::consume_proxy`] (generated by `#[service]`), cached,
    /// then returned.
    pub async fn get<T: ServiceConsumer>(&self) -> Option<Arc<T>> {
        let name = T::SERVICE_NAME;

        // Fast-path 1: already registered as a Provider.
        {
            let entries = self.entries.read().await;
            if let Some(entry) = entries.get(name) {
                return entry.instance.clone().downcast::<T>().ok();
            }
        }

        // Fast-path 2: already in the lazy cache.
        {
            let cache = self.lazy_cache.read().await;
            if let Some(instance) = cache.get(name) {
                return instance.clone().downcast::<T>().ok();
            }
        }

        // Slow-path: instantiate the Consumer proxy and cache it.
        let proxy: Arc<T> = T::consume_proxy();
        self.lazy_cache
            .write()
            .await
            .entry(name)
            .or_insert_with(|| proxy.clone() as Arc<dyn Any + Send + Sync>);

        Some(proxy)
    }

    /// Retrieves a proxy by its **type**, **blocking the current thread**.
    ///
    /// Synchronous twin of [`get`](Self::get): the same two fast paths (registered
    /// provider, then lazy cache) and the same lazy build through
    /// [`ServiceConsumer::consume_proxy`], with
    /// [`async_lock::RwLock::read_blocking`] / `write_blocking` in place of the
    /// awaited guards.
    ///
    /// Blocks on the locator's lock, so call it from a synchronous entry point (a
    /// `fn main` with no runtime) rather than from inside an async task.
    pub fn get_blocking<T: ServiceConsumer>(&self) -> Option<Arc<T>> {
        let name = T::SERVICE_NAME;

        // Fast-path 1: already registered as a Provider.
        {
            let entries = self.entries.read_blocking();
            if let Some(entry) = entries.get(name) {
                return entry.instance.clone().downcast::<T>().ok();
            }
        }

        // Fast-path 2: already in the lazy cache.
        {
            let cache = self.lazy_cache.read_blocking();
            if let Some(instance) = cache.get(name) {
                return instance.clone().downcast::<T>().ok();
            }
        }

        // Slow-path: instantiate the Consumer proxy and cache it.
        let proxy: Arc<T> = T::consume_proxy();
        self.lazy_cache
            .write_blocking()
            .entry(name)
            .or_insert_with(|| proxy.clone() as Arc<dyn Any + Send + Sync>);

        Some(proxy)
    }

    /// Registers a Provider service, storing its instance and lifecycle.
    ///
    /// Registration is keyed by the service's **logical name**: registering a
    /// name that is already present **replaces** the previous entry instead of
    /// adding a second one, so [`service_count`](Self::service_count) does not
    /// grow on a re-registration.
    ///
    /// # Returns
    /// - `true` when an entry under the same name was replaced;
    /// - `false` when the name was new and the entry was added.
    pub async fn register<T>(&self, service: Arc<T>) -> bool
    where
        T: ServiceLifecycle + ServiceNamed + ServiceInit + Any + Send + Sync + 'static,
    {
        let name: &'static str = T::SERVICE_NAME;
        let instance = service.clone() as Arc<dyn Any + Send + Sync>;
        let init = service.clone() as Arc<dyn ServiceInit>;
        let lifecycle = service as Arc<dyn ServiceLifecycle>;
        self.entries
            .write()
            .await
            .insert(
                name,
                ServiceEntry {
                    instance,
                    lifecycle,
                    init,
                },
            )
            .is_some()
    }

    /// Initializes all the registered services, **in dependency order**.
    ///
    /// The order comes from [`ServiceInit::dependencies`],
    /// and it only concerns the services registered in **this** process: a
    /// dependency that is not registered locally is treated as **external and
    /// never blocks** — it is ignored by the sort, with no discovery, no
    /// connection and no wait. A cyclic graph falls back to the registration
    /// order.
    ///
    /// A service whose `init()` returns `false` aborts the whole startup: the
    /// first failure is returned as `Err` and the remaining services are **not**
    /// initialized. There is no automatic retry.
    pub async fn initialize_all(&self) -> Result<(), String> {
        let snapshot: Vec<(&'static str, Arc<dyn ServiceLifecycle>, Vec<&'static str>)> = {
            let entries = self.entries.read().await;
            entries
                .iter()
                .map(|(name, entry)| (*name, entry.lifecycle.clone(), entry.init.dependencies()))
                .collect()
        };

        let names: Vec<&'static str> = snapshot.iter().map(|(name, _, _)| *name).collect();
        let deps: Vec<Vec<&'static str>> =
            snapshot.iter().map(|(_, _, deps)| deps.clone()).collect();

        for i in topological_order(&names, &deps) {
            let (name, lifecycle, _) = &snapshot[i];
            if !lifecycle.init().await {
                log::error!("[ServiceLocator] service '{name}' failed to initialize");
                return Err(format!("service '{name}' failed to initialize"));
            }
        }

        // Every provider has registered its channel: start the channel threads.
        crate::transport::start_registered_channels();
        Ok(())
    }
}

/// Returns the initialization indices in dependency order (Kahn's algorithm).
///
/// A dependency that is not in `names` is treated as **external** (provided by
/// another process) and never blocks. A dependency cycle falls back to the
/// registration order instead of dead-locking the process.
fn topological_order(names: &[&'static str], deps: &[Vec<&'static str>]) -> Vec<usize> {
    let registered: HashSet<&'static str> = names.iter().copied().collect();

    let mut remaining: Vec<usize> = (0..names.len()).collect();
    let mut done: HashSet<&'static str> = HashSet::with_capacity(names.len());
    let mut order: Vec<usize> = Vec::with_capacity(names.len());

    while !remaining.is_empty() {
        let mut next_remaining = Vec::new();
        let mut progressed = false;
        for &i in &remaining {
            let ready = deps[i]
                .iter()
                .all(|dep| done.contains(dep) || !registered.contains(dep));
            if ready {
                order.push(i);
                done.insert(names[i]);
                progressed = true;
            } else {
                next_remaining.push(i);
            }
        }
        remaining = next_remaining;
        if !progressed {
            log::warn!(
                "[ServiceLocator] dependency cycle among {:?}; using registration order",
                remaining.iter().map(|&i| names[i]).collect::<Vec<_>>()
            );
            order.append(&mut remaining);
        }
    }
    order
}

#[cfg(test)]
mod tests {
    use std::sync::Mutex;
    use std::sync::atomic::{AtomicUsize, Ordering};

    use super::*;

    /// Guards the **process-global** locator, which only [`initialize_all`]
    /// touches: it starts the registered transport channels, which is global
    /// state and cannot run on a per-test instance. Every other test builds its
    /// own [`ServiceLocator::new_for_test`] and needs no lock.
    fn locator_lock() -> &'static Mutex<()> {
        static LOCK: Mutex<()> = Mutex::new(());
        &LOCK
    }

    /// What a mock provider remembers: how it answers, and who observed it.
    struct MockState {
        init_result: bool,
        dependencies: Vec<&'static str>,
        init_calls: Arc<AtomicUsize>,
        init_order: Arc<Mutex<Vec<&'static str>>>,
    }

    impl Default for MockState {
        fn default() -> Self {
            Self {
                init_result: true,
                dependencies: Vec::new(),
                init_calls: Arc::new(AtomicUsize::new(0)),
                init_order: Arc::new(Mutex::new(Vec::new())),
            }
        }
    }

    /// Declares a provider mock. `SERVICE_NAME` is a constant, so two names need
    /// two types; every instance shares the same [`MockState`] shape.
    macro_rules! provider_mock {
        ($name:ident, $service:literal) => {
            struct $name(MockState);

            impl ServiceNamed for $name {
                const SERVICE_NAME: &'static str = $service;
            }

            #[async_trait::async_trait]
            impl ServiceInit for $name {
                fn dependencies(&self) -> Vec<&'static str> {
                    self.0.dependencies.clone()
                }
            }

            #[async_trait::async_trait]
            impl ServiceLifecycle for $name {
                async fn init(&self) -> bool {
                    self.0.init_calls.fetch_add(1, Ordering::Relaxed);
                    if let Ok(mut order) = self.0.init_order.lock() {
                        order.push($service);
                    }
                    self.0.init_result
                }
            }
        };
    }

    // A provider that is also its own consumer: `get::<T>` must hand back the
    // registered instance without ever building a proxy.
    provider_mock!(EchoService, "LocatorEcho");

    impl ServiceConsumer for EchoService {
        // `ServiceConsumer::consume_proxy` is a **static** constructor, so it
        // cannot read a per-instance counter. The tests assert the observable
        // property instead: a proxy built here would not be `Arc::ptr_eq` to the
        // registered provider, which is a stronger check than a call count.
        fn consume_proxy() -> Arc<Self> {
            Arc::new(EchoService(MockState::default()))
        }
    }

    // A consumer-only service: `get::<T>` must build it lazily, once.
    struct ConfigService;

    impl ServiceNamed for ConfigService {
        const SERVICE_NAME: &'static str = "LocatorConfig";
    }

    impl ServiceConsumer for ConfigService {
        fn consume_proxy() -> Arc<Self> {
            Arc::new(ConfigService)
        }
    }

    // A name shared by a provider and an unrelated consumer type.
    provider_mock!(NamesakeProvider, "LocatorNamesake");

    struct NamesakeConsumer;

    impl ServiceNamed for NamesakeConsumer {
        const SERVICE_NAME: &'static str = "LocatorNamesake";
    }

    impl ServiceConsumer for NamesakeConsumer {
        fn consume_proxy() -> Arc<Self> {
            Arc::new(NamesakeConsumer)
        }
    }

    provider_mock!(FirstService, "LocatorFirst");
    provider_mock!(SecondService, "LocatorSecond");
    provider_mock!(BrokenService, "LocatorBroken");

    #[test]
    fn a_registered_provider_is_handed_back_without_a_proxy() {
        let locator = ServiceLocator::new_for_test();

        let state = MockState {
            init_result: true,
            ..MockState::default()
        };
        let init_calls = state.init_calls.clone();
        let provider = Arc::new(EchoService(state));

        assert!(
            !pollster::block_on(locator.register(provider.clone())),
            "a fresh name is an addition, not a replacement"
        );
        // Absolute, not a delta: the registry is private to this test.
        assert_eq!(locator.service_count(), 1, "one name, one entry");
        assert!(locator.service_names().contains(&"LocatorEcho"));

        // Fast-path 1: the registered provider, by type. Getting the very same
        // instance back is itself the proof that no proxy was built.
        let fetched = pollster::block_on(locator.get::<EchoService>())
            .expect("a registered provider is returned");
        assert!(
            Arc::ptr_eq(&fetched, &provider),
            "the very same instance must come back"
        );
        assert_eq!(
            init_calls.load(Ordering::Relaxed),
            0,
            "registering a service runs no initialization hook"
        );
    }

    /// Re-registering a name **replaces** the previous entry: the count does not
    /// grow, and `register` says so. This is the regression guard for the
    /// order-dependent test that assumed a fresh registry.
    #[test]
    fn registering_the_same_name_twice_replaces_the_entry() {
        let locator = ServiceLocator::new_for_test();

        let first =
            pollster::block_on(locator.register(Arc::new(EchoService(MockState::default()))));
        let second =
            pollster::block_on(locator.register(Arc::new(EchoService(MockState::default()))));

        assert!(!first, "the name was new");
        assert!(second, "the second registration replaces the first");
        assert_eq!(locator.service_count(), 1, "one name maps to one entry");
    }

    #[test]
    fn an_unregistered_service_is_built_once_and_cached() {
        let locator = ServiceLocator::new_for_test();

        // Slow path: the proxy is built, then cached (fast-path 2 answers next).
        let first = pollster::block_on(locator.get::<ConfigService>()).expect("a proxy is built");
        let second = pollster::block_on(locator.get::<ConfigService>()).expect("the cache answers");

        // The same `Arc` twice is what "built once" means: a second build would
        // hand back a different allocation.
        assert!(Arc::ptr_eq(&first, &second), "the cached proxy is reused");
        assert_eq!(first.service_name(), "LocatorConfig");
        // A lazily built proxy is not a registered provider.
        assert!(!locator.service_names().contains(&"LocatorConfig"));
    }

    #[test]
    fn a_name_registered_under_another_type_is_not_returned() {
        let locator = ServiceLocator::new_for_test();
        pollster::block_on(locator.register(Arc::new(NamesakeProvider(MockState::default()))));

        // The name is registered, but the entry holds another concrete type: the
        // lookup reports nothing rather than handing back a foreign instance.
        assert!(pollster::block_on(locator.get::<NamesakeConsumer>()).is_none());
    }

    #[test]
    fn initialize_all_orders_dependencies_and_reports_a_failure() {
        // The only test that needs the process-wide locator: `initialize_all`
        // starts the registered transport channels, which is global state a
        // per-test instance would not exercise.
        let _guard = locator_lock().lock().unwrap_or_else(|e| e.into_inner());
        let locator = ServiceLocator::global();

        let init_order: Arc<Mutex<Vec<&'static str>>> = Arc::new(Mutex::new(Vec::new()));
        let second = Arc::new(SecondService(MockState {
            init_order: init_order.clone(),
            ..MockState::default()
        }));
        // `First` depends on `Second`, registered first: the sort must reorder.
        let first = Arc::new(FirstService(MockState {
            dependencies: vec!["LocatorSecond"],
            init_order: init_order.clone(),
            ..MockState::default()
        }));
        pollster::block_on(locator.register(first.clone()));
        pollster::block_on(locator.register(second.clone()));

        pollster::block_on(locator.initialize_all()).expect("every service initializes");

        let recorded = init_order.lock().expect("init order").clone();
        let first_at = recorded
            .iter()
            .position(|name| *name == "LocatorFirst")
            .expect("First was initialized");
        let second_at = recorded
            .iter()
            .position(|name| *name == "LocatorSecond")
            .expect("Second was initialized");
        assert!(
            second_at < first_at,
            "a dependency must initialize first: {recorded:?}"
        );
        assert_eq!(first.0.init_calls.load(Ordering::Relaxed), 1);
        assert_eq!(second.0.init_calls.load(Ordering::Relaxed), 1);

        // A provider that refuses to initialize aborts the pass, and names itself.
        let broken = Arc::new(BrokenService(MockState {
            init_result: false,
            ..MockState::default()
        }));
        pollster::block_on(locator.register(broken));
        let error = pollster::block_on(locator.initialize_all()).expect_err("the pass fails");
        assert!(error.contains("LocatorBroken"), "{error}");
    }

    #[test]
    fn shutdown_handles_are_registered_on_the_locator() {
        let locator = ServiceLocator::new_for_test();
        // Both handles complete immediately, so taking ownership of them is the
        // whole behaviour under test.
        locator.register_shutdown_handle(crate::rt::spawn_blocking(|| {}));
        locator.register_shutdown_thread(std::thread::spawn(|| {}));
    }

    #[test]
    fn dependencies_come_first() {
        // `DatabaseService` depends on `ConfigService`, registered after it.
        let names = ["DatabaseService", "ConfigService"];
        let deps = [vec!["ConfigService"], vec![]];
        assert_eq!(topological_order(&names, &deps), vec![1, 0]);
    }

    #[test]
    fn independent_services_keep_the_registration_order() {
        let names = ["A", "B", "C"];
        let deps = [vec![], vec![], vec![]];
        assert_eq!(topological_order(&names, &deps), vec![0, 1, 2]);
    }

    #[test]
    fn external_dependencies_do_not_block() {
        // `A` depends on a service provided by another process.
        let names = ["A"];
        let deps = [vec!["RemoteService"]];
        assert_eq!(topological_order(&names, &deps), vec![0]);
    }

    #[test]
    fn a_cycle_falls_back_to_the_registration_order() {
        let names = ["A", "B"];
        let deps = [vec!["B"], vec!["A"]];
        let order = topological_order(&names, &deps);
        assert_eq!(order.len(), 2);
        assert!(order.contains(&0) && order.contains(&1));
    }

    #[test]
    fn chained_dependencies_are_fully_ordered() {
        let names = ["C", "B", "A"];
        let deps = [vec!["B"], vec!["A"], vec![]];
        assert_eq!(topological_order(&names, &deps), vec![2, 1, 0]);
    }

    #[test]
    fn a_dependency_registered_by_another_process_is_external() {
        // Only `First` is local; its dependency belongs to another process and
        // must never hold the pass up.
        let names = ["LocatorFirst"];
        let deps = [vec!["LocatorSecond"]];
        assert_eq!(topological_order(&names, &deps), vec![0]);
    }

    #[test]
    fn a_self_dependency_is_a_cycle() {
        let names = ["A"];
        let deps = [vec!["A"]];
        // The fallback returns the remaining indices rather than looping forever.
        assert_eq!(topological_order(&names, &deps), vec![0]);
    }

    #[test]
    fn an_empty_registry_orders_nothing() {
        assert!(topological_order(&[], &[]).is_empty());
    }

    /// The blocking twin returns the very same registered instance, without
    /// entering a runtime.
    #[test]
    fn get_blocking_hands_back_the_registered_provider() {
        let locator = ServiceLocator::new_for_test();

        let provider = Arc::new(EchoService(MockState::default()));
        pollster::block_on(locator.register(provider.clone()));

        let fetched = locator
            .get_blocking::<EchoService>()
            .expect("a registered provider is returned");
        assert!(Arc::ptr_eq(&fetched, &provider));
    }

    /// The blocking twin builds a consumer proxy lazily, then serves it from the
    /// cache — a lazily built proxy is never a registered provider.
    #[test]
    fn get_blocking_builds_and_caches_a_consumer_proxy() {
        let locator = ServiceLocator::new_for_test();

        let first = locator
            .get_blocking::<ConfigService>()
            .expect("a proxy is built");
        let second = locator
            .get_blocking::<ConfigService>()
            .expect("the cache answers");

        assert!(Arc::ptr_eq(&first, &second), "the cached proxy is reused");
        assert_eq!(first.service_name(), "LocatorConfig");
        assert!(!locator.service_names().contains(&"LocatorConfig"));
    }
}
